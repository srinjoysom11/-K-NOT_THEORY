#!/usr/bin/env python
"""Regenerate wiki/lattice-length/tables-minimal-length.md from the CSVs in wiki/data and data/."""
import csv, os, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
rd = lambda p: list(csv.DictReader(open(os.path.join(ROOT, p), encoding='utf8')))
A1 = {r['knot']: r for r in rd('wiki/data/scharein2009_tableA1_min_step.csv')}
A2 = {r['knot']: r for r in rd('wiki/data/scharein2009_tableA2_lattice_stick.csv')}
proved = {'0_1': 'trivial', '3_1': 'proved [Diao93]', '4_1': 'proof outlined [Scharein09]', '5_1': 'proof outlined [Scharein09]'}
jvrr = {}  # P_K from [JvRR11] Table 3 where available
for line in '''0_1 3;3_1 3328;4_1 3648;5_1 6672;5_2 114912;6_1 6144;6_2 32832;6_3 3552;7_1 33960;7_2 336360;7_3 480;7_4 168;7_5 9456;7_6 34032;7_7 504;8_1 23736;8_2 91680;8_3 12;8_4 47856;8_5 1152;8_6 11040;8_7 48;8_8 3120;8_9 35280;8_10 1680;8_11 192;8_12 2592;8_13 26112;8_14 720;8_15 80208;8_16 96;8_17 53184;8_18 3552;8_19 13992;8_20 240;8_21 56040;9_1 345960;9_2 3281304;9_42 27744;9_47 13680;10_1 462576;10_2 871296'''.split(';'):
    k, v = line.split(); jvrr[k] = v

out = []
w = out.append
w('# Table of best-known minimal lattice lengths, SC lattice, prime knots ≤ 10 crossings\n')
w('*Generated by `wiki/tools/build_tables.py` — edit the CSVs, not this file.*\n')
w('Sources: Len upper bound S, number E of canonical minimal polygons found, number C of type-0 (length-preserving BFACF) classes — [Scharein09] Table A1; lattice stick upper bound — [Scharein09] Table A2; P_K (minimal polygons up to translation, both chiralities) — [JvRR11] Table 3 where computed. Polygons realising every S: `data/rechnitzer_SC_minimal.csv` (re-verified in this project, see `READING_LIST.md` §1).\n')
w('**Status:** only 3_1 (24), 4_1 (30), 5_1 (34) are exact; every other S is a numerical **upper bound** ([Scharein09] §1). E and C are lower bounds on the true counts ("not an exhaustive enumeration", [Scharein09] §5.3). The knot numbering follows [Scharein09] (10_1 … 10_165).\n')
w('Lattice stick column: `a→b` means the minimum over minimal-length polygons is a, and a separate stick-minimising search found b = a − k (the superscript k of Table A2).\n')
dist = collections.Counter(int(r['min_step_upper_bound_S']) for k, r in A1.items() if k != '0_1')
w('## Distribution of S over the 249 knots\n')
w('| S | ' + ' | '.join(str(s) for s in sorted(dist)) + ' |')
w('|---|' + '---|' * len(dist))
w('| #knots | ' + ' | '.join(str(dist[s]) for s in sorted(dist)) + ' |\n')
w('Range of S by crossing number ([Scharein09] Table 3): alternating 3: 24; 4: 30; 5: 34–36; 6: 40; 7: 44–46; 8: 48–52; 9: 54–58; 10: 58–64. Non-alternating 8: 42–46; 9: 48–52; 10: 48–58. "Non-alternating knots generally require fewer steps."\n')
w('Number n of prime knot types realisable with ≤ s steps ([Scharein09] Table 2): s=4:1, 24:2, 30:3, 34:4, 36:5, 40:8, 42:9, 44:14, 46:18, 48:22, 50:40, 52:49, 54:74, 56:119, 58:130, 60:175, 62:244, 64:250.\n')
by = collections.defaultdict(list)
for k in A1:
    by[int(k.split('_')[0])].append(k)
for c in sorted(by):
    w('## %d crossings\n' % c if c else '## Unknot\n')
    w('| knot | Len ≤ S | status | E canonical | C type-0 classes | P_K [JvRR11] | s_L ≤ |')
    w('|---|---|---|---|---|---|---|')
    for k in by[c]:
        a, b = A1[k], A2[k]
        s = int(b['lattice_stick_upper_bound_from_min_step_polygons']); sup = b['superscript_k_improvement_by_separate_search']
        st = '%d→%d' % (s, s - int(sup)) if sup else str(s)
        w('| %s | %s | %s | %s | %s | %s | %s |' % (k, a['min_step_upper_bound_S'], proved.get(k, 'numerical'), a['canonical_total_E'], a['type0_classes_C'], jvrr.get(k, ''), st))
    w('')
open(os.path.join(ROOT, 'wiki/lattice-length/tables-minimal-length.md'), 'w', encoding='utf8').write('\n'.join(out))
print('rows', len(A1))
