#!/usr/bin/env python
"""Regenerate wiki/SOURCES.md: one row per citation key with title, authors, venue,
file, extract link and the topic pages that cite it.

    python wiki/tools/build_sources.py
"""
import os, re, glob

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
WIKI = os.path.join(ROOT, 'wiki')
rows = [l.split('\t') for l in open(os.path.join(WIKI, 'tools', 'sources.tsv'), encoding='utf8').read().splitlines()[1:] if l.strip()]

pages = [p for p in glob.glob(os.path.join(WIKI, '**', '*.md'), recursive=True)
         if os.sep + '_extracts' + os.sep not in p and not p.endswith('SOURCES.md')]
cites = {}
for p in pages:
    txt = open(p, encoding='utf8').read()
    rel = os.path.relpath(p, WIKI).replace('\\', '/')
    known = {r[0] for r in rows}
    for k in set(re.findall(r'\[([A-Za-z0-9]+)\]', txt)) & known:
        cites.setdefault(k, []).append(rel)


def meta(key):
    f = os.path.join(WIKI, '_extracts', key + '.md')
    if not os.path.exists(f):
        return None
    t = open(f, encoding='utf8').read()
    title = re.search(r'^# \S+ — (.+)$', t, re.M)
    auth = re.search(r'\*\*Authors:\*\*\s*(.+)', t)
    ven = re.search(r'\*\*Venue / year / identifiers:\*\*\s*(.+)', t)
    clean = lambda m: m.group(1).strip().replace('|', '/') if m else ''
    return clean(title), clean(auth), clean(ven)


out = ['# Sources', '',
       'Generated by `tools/build_sources.py` from `tools/sources.tsv` and the `_extracts/` headers — do not edit by hand.',
       'Citation keys `[Key]` used throughout the wiki resolve here. "Cited from" lists topic pages that use the key.', '',
       '| key | title | authors | venue / id | extract | cited from |', '|---|---|---|---|---|---|']
for key, batch, path in rows:
    m = meta(key)
    title, auth, ven = m if m else ('*(no extract yet)*', '', '')
    if len(auth) > 80:
        auth = auth[:77] + '…'
    if len(ven) > 90:
        ven = ven[:87] + '…'
    ex = f'[x](_extracts/{key}.md)' if m else '—'
    cf = ', '.join(f'[{os.path.basename(c)[:-3]}]({c})' for c in sorted(cites.get(key, []))) or '—'
    out.append(f'| {key} | {title} | {auth} | {ven} | {ex} | {cf} |')
out += ['', 'PDF paths: see `tools/sources.tsv`.', '']
open(os.path.join(WIKI, 'SOURCES.md'), 'w', encoding='utf8').write('\n'.join(out))
print('wrote SOURCES.md with', len(rows), 'keys;', sum(1 for r in rows if meta(r[0])), 'have extracts')
