#!/usr/bin/env python3
"""Builds site/tables.js from the repository's transcribed literature tables (nothing typed by hand).
Source: wiki/data/scharein2009_tableA1_min_step.csv, Table A1 of Scharein et al. (2009):
for every prime knot with at most 10 crossings, the best known upper bound S on the minimal lattice
length, the number E of canonical minimal polygons found and the number C of length-preserving classes.
Run from anywhere:  python3 research/exact/site/build_tables.py"""
import csv, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "wiki", "data", "scharein2009_tableA1_min_step.csv")
rows = []
with open(SRC) as f:
    for r in csv.DictReader(f):
        rows.append([r["knot"], int(r["min_step_upper_bound_S"]), int(r["canonical_total_E"]), int(r["type0_classes_C"])])
with open(os.path.join(HERE, "tables.js"), "w") as f:
    f.write("// generated by build_tables.py from wiki/data/scharein2009_tableA1_min_step.csv; do not edit\n")
    f.write("// [knot, best known upper bound S on Len, canonical minimal polygons found E, length-preserving classes C]\n")
    f.write("export const TABLE_A1 = " + json.dumps(rows, separators=(",", ":")) + ";\n")
print(len(rows), "knots")
