"""
run_search.py -- BFACF annealing from diagram seeds, with verification.

  py -3.12 research/code/run_search.py --crossings 11 --rounds 3 --runs 8 --tag c11

For every knot: round 1 starts `runs` independent annealing runs (RNG seeds
base+1..base+runs) from the diagram seed in research/data/seeds.json; each later
round restarts `runs` runs from the shortest word found so far. The provenance
chain "round:rngseed" is stored so every result can be regenerated by re-running
bfacf with the same arguments.

Verification of the final word (function verify):
  (a) it is a closed self-avoiding lattice polygon (code/latticeknot.py),
  (b) SnapPy identifies the polygon's complement as the named knot
      (the repo's own checker, code/latticeknot.identify), and
  (c) the Alexander polynomial of the polygon equals that of the source diagram
      (elementary cross-check; the only check available for torus knots,
      which are not hyperbolic).
"""
import argparse
import csv
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, os.path.join(ROOT, '..', 'code'))
sys.path.insert(0, HERE)
import latticeknot as lk  # noqa: E402
import seeds as sd  # noqa: E402
from alexander import alexander  # noqa: E402

EXE = os.path.join(HERE, 'bfacf.exe')


def anneal(word, rng, a):
    r = subprocess.run([EXE, word, str(rng), str(a.cycles), str(a.nhigh), str(a.nlow), str(a.zmax), str(a.zlow)],
                       capture_output=True, text=True)
    if not r.stdout.startswith('BEST'):
        raise RuntimeError(r.stderr)
    _, n, w = r.stdout.split()
    assert int(n) == len(w)
    return w


def alex(link):
    return alexander(link.PD_code())


def verify(word, sname):
    import spherogram
    v = lk.word_to_vertices(word)
    if not lk.is_lattice_polygon([v]):
        return False, 'not a polygon'
    L = lk.to_spherogram([v])
    L.simplify('global')
    ref = spherogram.Link(sname)
    a_ok = alex(L) == alex(ref)
    try:
        ids = [str(x).split('(')[0] for x in L.exterior().identify()]
    except Exception:
        ids = []
    if sname in ids:
        return a_ok, 'snappy+alexander' if a_ok else 'snappy ok, alexander MISMATCH'
    if not ids and not ref.exterior().identify():
        # non-hyperbolic (torus) knot: Alexander polynomial + knot Floer homology only.
        # SnapPy cannot name these; HFK is compared with the diagram and its mirror image.
        h = L.knot_floer_homology()
        ok = a_ok and any(h['ranks'] == r.knot_floer_homology()['ranks'] for r in (ref, ref.mirror()))
        return ok, 'non-hyperbolic: alexander+HFK' if ok else 'non-hyperbolic MISMATCH'
    return False, 'identify gave ' + ','.join(ids[:3])


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--crossings', type=int, nargs='+', required=True)
    p.add_argument('--rounds', type=int, default=3)
    p.add_argument('--runs', type=int, default=8)
    p.add_argument('--cycles', type=int, default=100)
    p.add_argument('--nhigh', type=int, default=100000)
    p.add_argument('--nlow', type=int, default=60000)
    p.add_argument('--zmax', type=float, default=0.2)
    p.add_argument('--zlow', type=float, default=0.02)
    p.add_argument('--base', type=int, default=0, help='RNG seeds are base+round*1000+run')
    p.add_argument('--workers', type=int, default=10)
    p.add_argument('--tag', required=True)
    p.add_argument('--only', nargs='*')
    p.add_argument('--start', help='json {knot: word} to start from instead of diagram seeds')
    a = p.parse_args()

    seeds = json.load(open(os.path.join(ROOT, 'data', 'seeds.json')))
    start = json.load(open(a.start)) if a.start else seeds
    known = {}
    for row in csv.DictReader(open(os.path.join(ROOT, '..', 'data', 'rechnitzer_SC_minimal.csv'))):
        known[row['knot']] = int(row['best_known_length'])
    knots = [k for c in a.crossings for k in sd.knot_list(c)]
    if a.only:
        knots = [k for k in knots if k[0] in a.only]
    out_path = os.path.join(ROOT, 'out', f'{a.tag}.csv')
    done = set()
    if os.path.exists(out_path):
        done = {r['knot'] for r in csv.DictReader(open(out_path))}
    f = open(out_path, 'a', newline='')
    wr = csv.writer(f)
    if not done:
        wr.writerow(['knot', 'start_length', 'best_length', 'literature_bound', 'verified', 'check', 'chain', 'word'])
    t0 = time.time()

    def work(k):
        name, sname = k
        best, chain = start[name], []
        for rd in range(1, a.rounds + 1):
            rngs = [a.base + rd * 1000 + i for i in range(1, a.runs + 1)]
            res = [(anneal(best, r, a), r) for r in rngs]
            w, r = min(res, key=lambda t: (len(t[0]), t[1]))
            if len(w) < len(best):
                best = w
                chain.append(f'{rd}:{r}')
        return name, sname, best, chain

    todo = [k for k in knots if k[0] not in done]
    with ThreadPoolExecutor(a.workers) as ex:
        for i, (name, sname, best, chain) in enumerate(ex.map(work, todo)):
            ok, how = verify(best, sname)
            wr.writerow([name, len(start[name]), len(best), known.get(name, ''), ok, how, ' '.join(chain), best])
            f.flush()
            if i % 25 == 0:
                print(f'{i + 1}/{len(todo)} {name} {len(best)} {known.get(name, "")} {ok} {how} [{time.time() - t0:.0f}s]', flush=True)
    print('done', time.time() - t0)


if __name__ == '__main__':
    main()
